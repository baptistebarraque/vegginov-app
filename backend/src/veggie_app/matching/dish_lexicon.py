_IRREGULAR_FEMININES = {"grec": "grecque", "turc": "turque", "thaï": "thaïe"}


def _feminine(adjective: str) -> str:
    if adjective in _IRREGULAR_FEMININES:
        return _IRREGULAR_FEMININES[adjective]
    if adjective.endswith("ien"):
        return adjective + "ne"
    if adjective.endswith("e"):
        return adjective
    return adjective + "e"


for _adjective, _cuisine in CUISINE_ADJECTIVES.items():
    DISH_LEXICON.setdefault(_adjective, ((), _cuisine))
    DISH_LEXICON.setdefault(_feminine(_adjective), ((), _cuisine))
